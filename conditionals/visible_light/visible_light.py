num=int(input())
if 380 <=  num < 450:
    print("Violet")
elif 450 <= num < 495:
    print("Blue")
elif 495 <= num < 570:
    print("Green")
elif 570 <= num < 590:
    print("Yellow")
elif 590 <= num < 620:
    print("Orange")
elif 620 <= num <= 750:
    print("Red")
else:
    print("Outside visible spectrum")                  